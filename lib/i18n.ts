import { createContext, useContext, useEffect, useMemo, useState } from 'react';

export function getSavedLocale(): Locale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  try {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (!saved) return DEFAULT_LOCALE;
    if (saved === 'en' || saved === 'fr') return saved;
    return DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

export function setSavedLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // ignore
  }
}

export function translate(key: string, locale?: Locale): string {
  const loc = locale || getSavedLocale();
  const dict = dictionaries[loc] || dictionaries[DEFAULT_LOCALE];
  return dict[key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
}

export function t(key: string, locale?: Locale): string {
  return translate(key, locale);
}

